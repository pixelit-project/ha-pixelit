import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = "custom_components/pixelit/www/pixelit-card.js";
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/pixelit-card.js"],
  outfile: output,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: false,
  legalComments: "inline",
  banner: {
    js: "// Generated by npm run build from src/pixelit-card.js. Do not edit directly.\n// Copyright (c) 2026 Pissbirne and PixelIt project contributors. MIT license.",
  },
  metafile: true,
  write: false,
});
if (
  result.outputFiles.length !== 1 ||
  Object.values(result.metafile.outputs).some(({ imports }) => imports.length)
) {
  throw new Error(
    "The card must be a single self-contained module without runtime imports.",
  );
}
const generated = result.outputFiles[0].contents;
const path = new URL("../" + output, import.meta.url);
if (process.argv.includes("--check")) {
  const committed = await readFile(path);
  if (!committed.equals(Buffer.from(generated))) {
    throw new Error(
      "Shipped card differs from source. Run npm run build to regenerate it.",
    );
  }
  console.log("Shipped card matches the source build.");
} else {
  await writeFile(path, generated);
}
